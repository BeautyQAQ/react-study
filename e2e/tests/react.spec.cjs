const { test, expect } = require('../fixtures.cjs')
const { communityURL, api, registerUser, loginCommunityUI, assertNoOverflow } = require('../support.cjs')
const url = path => `${communityURL}/#${path}`

async function revealNavigation(page) {
  const toggle = page.getByRole('button', { name: '展开导航', exact: true })
  if (await toggle.isVisible()) await toggle.click()
}

test('社区首页可进入井字棋，保留平局、胜负、回看与主题偏好', async ({ page }, testInfo) => {
  await page.goto(url('/'))
  await expect(page.getByRole('tab', { name: '最新主题', exact: true })).toBeVisible()
  await revealNavigation(page)
  await page.getByRole('navigation', { name: '社区导航' }).getByRole('link', { name: '井字棋', exact: true }).click()
  const squares = page.getByRole('group', { name: 'Tic-tac-toe board' }).getByRole('button')
  await expect(squares).toHaveCount(9)
  for (const position of [0, 1, 2, 4, 3, 5, 7, 6, 8]) await squares.nth(position).click()
  await expect(page.getByText('Draw!', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'New game', exact: true }).click()
  for (const position of [0, 3, 1, 4, 2]) await squares.nth(position).click()
  await expect(page.getByText('Winner: X', { exact: true })).toBeVisible()
  await expect(page.locator('.square-winning')).toHaveCount(3)
  await page.getByRole('button', { name: 'Go to move #1', exact: true }).click()
  await squares.nth(8).click()
  await expect(squares.nth(8)).toHaveText('O')
  await expect(page.getByRole('listitem')).toHaveCount(3)
  await assertNoOverflow(page)
  await revealNavigation(page)
  await page.getByRole('button', { name: '深色模式', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.screenshot({ path: testInfo.outputPath('tic-tac-toe.png'), fullPage: true, animations: 'disabled' })
  await assertNoOverflow(page)
})

test('发帖登录保护通过回车登录后返回原入口，登录状态可刷新恢复', async ({ page }) => {
  const user = await registerUser()
  await page.goto(url('/post/create'))
  await expect(page).toHaveURL(/#\/login\?redirect=/)
  await page.getByLabel('账号', { exact: true }).fill(user.username)
  await page.getByLabel('密码', { exact: true }).fill(user.password)
  const pending = page.waitForResponse(response => new URL(response.url()).pathname === '/api/ums/user/login' && response.request().method() === 'POST')
  await page.getByLabel('密码', { exact: true }).press('Enter')
  expect((await pending).status()).toBe(200)
  await expect(page.getByLabel('标题', { exact: true })).toBeVisible()
  await expect(page).toHaveURL(/#\/post\/create\?draft=/)
  await page.reload()
  await expect(page.getByLabel('标题', { exact: true })).toBeVisible()
  await assertNoOverflow(page)
})

test('个人资料、主页隐私、设置归属和主动修改密码形成闭环', async ({ page }) => {
  const user = await registerUser(), other = await registerUser()
  const session = await loginCommunityUI(page, user)
  await page.goto(url(`/member/${user.username}/setting`))
  await page.getByLabel('昵称', { exact: true }).fill('React 社区成员')
  await page.getByLabel('简介', { exact: true }).fill('这是通过 React 页面保存的个人简介。')
  let pending = page.waitForResponse(response => new URL(response.url()).pathname === '/api/ums/user/profile' && response.request().method() === 'POST')
  await page.getByRole('button', { name: '保存资料', exact: true }).click()
  expect((await pending).status()).toBe(200)
  await page.goto(url(`/member/${user.username}/home`))
  await expect(page.getByRole('heading', { name: 'React 社区成员', exact: true })).toBeVisible()
  await expect(page.getByText('这是通过 React 页面保存的个人简介。', { exact: true })).toBeVisible()
  await expect(page.locator('#main-content')).not.toContainText(user.email)
  await page.goto(url(`/member/${other.username}/setting`))
  await expect(page).toHaveURL(/#\/$/)
  await page.goto(url(`/member/${user.username}/setting`))
  const password = `Changed_${Date.now()}_9a`
  await page.getByLabel('当前密码', { exact: true }).fill(user.password)
  await page.getByLabel('新密码', { exact: true }).fill(password)
  await page.getByLabel('确认新密码', { exact: true }).fill(password)
  pending = page.waitForResponse(response => new URL(response.url()).pathname === '/api/ums/user/password' && response.request().method() === 'POST')
  await page.getByRole('button', { name: '更新密码', exact: true }).click()
  expect((await pending).status()).toBe(200)
  await expect(page).toHaveURL(/#\/login$/)
  await api(communityURL, '/api/ums/user/info', { token: session.token, expected: 401 })
  await loginCommunityUI(page, { ...user, password })
  await assertNoOverflow(page)
})
