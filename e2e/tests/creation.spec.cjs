const { test, expect } = require('../fixtures.cjs')
const {
  communityURL, adminURL, api, registerUser, loginCommunityUI, adminLogin, reviewPost, unique,
  draftId, draftPublishPath, assertNoOverflow,
} = require('../support.cjs')

const url = path => `${communityURL}/#${path}`
const titleInput = page => page.getByLabel('标题', { exact: true })
const bodyInput = page => page.getByLabel('内容', { exact: true })
const saved = page => expect(page.locator('.draft-status')).toHaveText(/^草稿已保存 \d/)

async function logout(page) {
  const menu = page.getByRole('button', { name: '展开导航', exact: true })
  if (await menu.isVisible()) await menu.click()
  await page.locator('.account-menu summary').click()
  const pending = page.waitForResponse(response => new URL(response.url()).pathname === '/api/ums/user/logout' && response.request().method() === 'POST')
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  expect((await pending).status()).toBe(200)
  await expect(page).toHaveURL(/#\/$/)
}

async function publish(page) {
  const pending = page.waitForResponse(response => new URL(response.url()).pathname === draftPublishPath(page) && response.request().method() === 'POST')
  await page.getByRole('button', { name: '提交审核', exact: true }).click()
  const response = await pending
  expect(response.status()).toBe(200)
  return (await response.json()).data
}

test('精华展示和关注动态遵守公开状态、当前账号与取消关注', async ({ page }, testInfo) => {
  const author = await registerUser(), reader = await registerUser(), stranger = await registerUser()
  const title = unique('精华主题'), ordinaryTitle = unique('作者主题'), strangerTitle = unique('未关注主题')
  const create = (user, title) => api(communityURL, '/api/post/add', { method: 'POST', token: user.token, data: { title, content: '内容发现验收', tags: ['发现'] } })
  const featured = (await create(author, title)).data
  const ordinary = (await create(author, ordinaryTitle)).data, unrelated = (await create(stranger, strangerTitle)).data
  const admin = await adminLogin()
  await reviewPost(ordinary.id, admin); await reviewPost(unrelated.id, admin)
  const moderate = status => reviewPost(featured.id, admin, { status, top: true, essence: true, reason: '内容发现验收' })
  await moderate('PUBLISHED')
  await page.goto(url('/?tab=following'))
  await expect(page.getByRole('link', { name: '登录查看关注动态', exact: true })).toBeVisible()
  await api(communityURL, '/api/me/feed', { expected: 401 })
  await page.getByRole('tab', { name: '精华', exact: true }).click()
  const featuredRow = page.locator('article.post-row').filter({ hasText: title })
  await expect(featuredRow).toContainText('精华'); await expect(featuredRow).toContainText('置顶')
  await page.screenshot({ path: testInfo.outputPath('discovery.png'), fullPage: true, animations: 'disabled' })
  await featuredRow.getByRole('link', { name: title, exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`#/post/${featured.id}$`))
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await expect(page.locator('#main-content .badge').filter({ hasText: /^精华$/ })).toBeVisible()
  await expect(page.locator('#main-content .badge').filter({ hasText: /^置顶$/ })).toBeVisible()
  await assertNoOverflow(page)
  await moderate('HIDDEN')
  const hiddenListing = page.waitForResponse(response => new URL(response.url()).pathname === '/api/post/list' && new URL(response.url()).searchParams.get('tab') === 'essence')
  await page.goto(url('/?tab=essence'))
  expect((await hiddenListing).status()).toBe(200)
  await expect(page.locator('.post-list[aria-busy="true"]')).toBeHidden()
  await expect(page.locator('article.post-row').filter({ hasText: title })).toHaveCount(0)
  await moderate('PUBLISHED')
  await api(communityURL, `/api/users/${author.username}/follow`, { method: 'POST', token: reader.token })
  await loginCommunityUI(page, reader)
  await page.goto(url('/?tab=following'))
  await expect(page.locator('article.post-row').filter({ hasText: title })).toBeVisible()
  await expect(page.locator('article.post-row').filter({ hasText: ordinaryTitle })).toBeVisible()
  await expect(page.locator('article.post-row').filter({ hasText: strangerTitle })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('tab', { name: '关注动态', exact: true })).toHaveAttribute('aria-selected', 'true')
  await api(communityURL, `/api/users/${author.username}/follow`, { method: 'DELETE', token: reader.token })
  await page.reload()
  await expect(page.locator('article.post-row')).toHaveCount(0)
  await expect(page.getByText('关注的人还没有公开主题，去发现感兴趣的作者吧', { exact: true })).toBeVisible()
  await assertNoOverflow(page)
})

test('草稿在刷新前保留输入、账号间隔离、草稿箱续写发布及删除形成闭环', async ({ page }, testInfo) => {
  const author = await registerUser(), other = await registerUser()
  await loginCommunityUI(page, author)
  await page.goto(url('/post/create'))
  const title = unique('恢复草稿'), content = '## 刷新恢复\n\n尚未发布的正文 🌊'
  await titleInput(page).fill(title); await bodyInput(page).fill(content)
  const id = draftId(page)
  // Reload immediately, before the debounce is guaranteed to have reached the server.
  await page.reload()
  await expect(titleInput(page)).toHaveValue(title); await expect(bodyInput(page)).toHaveValue(content)
  await saved(page)
  await page.screenshot({ path: testInfo.outputPath('draft-editor.png'), fullPage: true, animations: 'disabled' })
  const draft = (await api(communityURL, `/api/me/drafts/${id}`, { token: author.token })).data
  expect(draft.content).toBe(content)
  expect((await api(communityURL, `/api/post/list?query=${encodeURIComponent(title)}`)).data.totalElements).toBe(0)
  await api(communityURL, `/api/me/drafts/${id}`, { token: other.token, expected: 404 })
  await page.locator('.section-heading').getByRole('link', { name: '草稿箱', exact: true }).click()
  await expect(page.locator('article.draft-row').filter({ hasText: title })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('draft-box.png'), fullPage: true, animations: 'disabled' })
  await logout(page); await loginCommunityUI(page, other)
  await page.goto(url('/me/drafts'))
  await expect(page.locator('article.draft-row')).toHaveCount(0)
  await logout(page); await loginCommunityUI(page, author)
  await page.goto(url('/me/drafts'))
  await page.locator('article.draft-row').filter({ hasText: title }).getByRole('link', { name: '继续编辑', exact: true }).click()
  await expect(bodyInput(page)).toHaveValue(content)
  await bodyInput(page).fill(`${content}\n\n继续创作并发布。`)
  const post = await publish(page)
  await expect(page).toHaveURL(new RegExp(`#/me/posts/${post.id}$`))
  expect(post.status).toBe('PENDING')
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await api(communityURL, `/api/me/drafts/${id}`, { token: author.token, expected: 404 })
  await api(communityURL, `/api/me/drafts/${id}/publish`, { method: 'POST', token: author.token, data: { version: draft.version }, expected: 404 })
  expect((await api(communityURL, `/api/post/list?query=${encodeURIComponent(title)}`)).data.totalElements).toBe(0)
  await api(communityURL, `/api/post/${post.id}`, { expected: 404 })
  await reviewPost(post.id, await adminLogin())
  expect((await api(communityURL, `/api/post/list?query=${encodeURIComponent(title)}`)).data.totalElements).toBe(1)
  await page.goto(url('/post/create'))
  await titleInput(page).fill(unique('删除草稿'))
  await saved(page)
  const deletedId = draftId(page)
  await page.getByRole('link', { name: '返回草稿箱', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  const pending = page.waitForResponse(response => new URL(response.url()).pathname === `/api/me/drafts/${deletedId}` && response.request().method() === 'DELETE')
  await page.locator('article.draft-row').getByRole('button', { name: '删除', exact: true }).click()
  expect((await pending).status()).toBe(200)
  await expect(page.locator('article.draft-row')).toHaveCount(0)
  await assertNoOverflow(page)
})

test('断网草稿可恢复同步，版本冲突保留正文并允许复制为新主题', async ({ page, context }) => {
  const author = await registerUser()
  await loginCommunityUI(page, author)
  await page.goto(url('/post/create'))
  await titleInput(page).fill(unique('离线草稿')); await bodyInput(page).fill('第一版正文')
  await saved(page)
  const id = draftId(page)
  await context.setOffline(true)
  try {
    await bodyInput(page).fill('断网期间继续输入的正文 🌊')
    await expect(page.locator('.draft-status')).toContainText('内容已保留在此浏览器')
  } finally { await context.setOffline(false) }
  await page.reload()
  await expect(bodyInput(page)).toHaveValue('断网期间继续输入的正文 🌊')
  await saved(page)
  const current = (await api(communityURL, `/api/me/drafts/${id}`, { token: author.token })).data
  await api(communityURL, `/api/me/drafts/${id}`, { method: 'PUT', token: author.token, data: { ...current, content: '另一页面已保存的正文' } })
  await bodyInput(page).fill('当前页面尚未同步的正文，需要保留')
  await expect(page.locator('.draft-status')).toContainText('草稿已在其他页面更新')
  await expect(bodyInput(page)).toHaveValue('当前页面尚未同步的正文，需要保留')
  await expect(page.getByRole('button', { name: '提交审核', exact: true })).toBeDisabled()
  expect((await api(communityURL, `/api/me/drafts/${id}`, { token: author.token })).data.content).toBe('另一页面已保存的正文')
  await page.getByRole('button', { name: '将当前内容复制为新主题', exact: true }).click()
  await expect.poll(() => draftId(page)).not.toBe(id)
  await expect(bodyInput(page)).toHaveValue('当前页面尚未同步的正文，需要保留')
  await saved(page)
  await expect(page.getByRole('button', { name: '提交审核', exact: true })).toBeEnabled()
  await assertNoOverflow(page)
})
